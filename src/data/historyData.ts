// Quick helper to search all nodes recursively
export function searchHistoryNodes(query: string, node: HistoryNode = INDIAN_HISTORY_DATA): HistoryNode[] {
  if (!query.trim()) return [];
  const cleanQuery = query.trim().toLowerCase();
  const results: HistoryNode[] = [];

  function traverse(curr: HistoryNode) {
    const titleMatch = curr.title.toLowerCase().includes(cleanQuery);
    const subtitleMatch = curr.subtitle?.toLowerCase().includes(cleanQuery);
    const descMatch = curr.description.toLowerCase().includes(cleanQuery);
    const keyMatch = curr.keyPoints.some(k => k.toLowerCase().includes(cleanQuery));
    const factsMatch = curr.examFacts?.some(f => f.toLowerCase().includes(cleanQuery));
    const sitesMatch = curr.sites?.some(s => s.toLowerCase().includes(cleanQuery));
    const discMatch = curr.discoverers?.some(d => d.toLowerCase().includes(cleanQuery));

    if (titleMatch || subtitleMatch || descMatch || keyMatch || factsMatch || sitesMatch || discMatch) {
      results.push(curr);
    }

    if (curr.children) {
      for (const child of curr.children) {
        traverse(child);
      }
    }
  }

  traverse(node);
  return results;
}

// Find a node by its ID
export function findNodeById(id: string, node: HistoryNode = INDIAN_HISTORY_DATA): HistoryNode | null {
  if (node.id === id) return node;
  if (node.children) {
    for (const child of node.children) {
      const res = findNodeById(id, child);
      if (res) return res;
    }
  }
  return null;
}

// Find parent path IDs for automatic expansion
export function findParentPath(id: string, node: HistoryNode = INDIAN_HISTORY_DATA, path: string[] = []): string[] | null {
  if (node.id === id) return path;
  if (node.children) {
    for (const child of node.children) {
      const res = findParentPath(id, child, [...path, node.id]);
      if (res) return res;
    }
  }
  return null;
}

// Gather all flashcard items for Exam Revision Mode
export interface ExamFlashcard {
  id: string;
  topic: string;
  category: string;
  question: string;
  answer: string;
  sourcePage: number;
}

export function getAllExamFlashcards(): ExamFlashcard[] {
  const cards: ExamFlashcard[] = [];

  function traverse(n: HistoryNode) {
    if (n.examFacts && n.examFacts.length > 0) {
      n.examFacts.forEach((fact, idx) => {
        cards.push({
          id: `${n.id}-fact-${idx}`,
          topic: n.title,
          category: n.period === "ancient" ? "प्राचीन भारत" : n.period === "medieval" ? "मध्यकालीन भारत" : "आधुनिक भारत",
          question: `[${n.title}] से संबंधित महत्वपूर्ण परीक्षा तथ्य क्या है?`,
          answer: fact,
          sourcePage: n.sourcePages[0] || 1,
        });
      });
    }
    if (n.children) {
      n.children.forEach(traverse);
    }
  }

  traverse(INDIAN_HISTORY_DATA);
  return cards;
}
